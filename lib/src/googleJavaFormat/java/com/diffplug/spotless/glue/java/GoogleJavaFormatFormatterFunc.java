package com.diffplug.spotless.glue.java;

import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.Objects;

import javax.annotation.Nonnull;

import com.google.googlejavaformat.java.Formatter;
import com.google.googlejavaformat.java.FormatterException;
import com.google.googlejavaformat.java.ImportOrderer;
import com.google.googlejavaformat.java.JavaFormatterOptions;
import com.google.googlejavaformat.java.JavaFormatterOptions.Style;
import com.google.googlejavaformat.java.RemoveUnusedImports;
import com.google.googlejavaformat.java.StringWrapper;

import com.diffplug.spotless.FormatterFunc;

// Used via reflection by the Gradle plugin.
@SuppressWarnings("unused")
public class GoogleJavaFormatFormatterFunc implements FormatterFunc {

	@Nonnull
	private final Formatter formatter;

	@Nonnull
	private final String version;

	@Nonnull
	private final Style formatterStyle;

	private final boolean reflowStrings;

	private final boolean reorderImports;

	public GoogleJavaFormatFormatterFunc(@Nonnull String version, @Nonnull String style, boolean reflowStrings, boolean reorderImports, boolean formatJavadoc, int maxLineLength) {
		this.version = Objects.requireNonNull(version);
		this.formatterStyle = toStyle(style);
		this.reflowStrings = reflowStrings;
		this.reorderImports = reorderImports;

		Style effectiveStyle = formatterStyle;
		if (maxLineLength > 0) {
			effectiveStyle = withMaxLineLength(formatterStyle, maxLineLength, version);
		}
		JavaFormatterOptions.Builder builder = JavaFormatterOptions.builder().style(effectiveStyle);
		if (!formatJavadoc) {
			builder = builder.formatJavadoc(false);
		}
		this.formatter = new Formatter(builder.build());
	}

	/**
	 * Parses a style name without calling {@code Style.valueOf}, which existed only while
	 * {@code Style} was an enum (google-java-format {@literal <=} 1.36); since 1.37 it is a record,
	 * but the {@code GOOGLE} and {@code AOSP} constants are present in both.
	 */
	@Nonnull
	private static Style toStyle(@Nonnull String style) {
		switch (Objects.requireNonNull(style)) {
		case "GOOGLE":
			return Style.GOOGLE;
		case "AOSP":
			return Style.AOSP;
		default:
			throw new IllegalArgumentException("style must be GOOGLE or AOSP, but was: " + style);
		}
	}

	/**
	 * Sets the column limit on the style's builder. That builder exists only in google-java-format
	 * 1.37.0+, while this glue code is compiled against 1.28.0 so that it keeps working on older
	 * versions, hence the reflection (https://github.com/diffplug/spotless/issues/3151).
	 * Methods are looked up on the public {@code Style$Builder} type rather than on the runtime
	 * class of the builder, because the runtime class generated by AutoBuilder is package-private.
	 */
	@Nonnull
	private static Style withMaxLineLength(@Nonnull Style style, int maxLineLength, @Nonnull String version) {
		try {
			Method createBuilder = Style.class.getMethod("builder");
			Class<?> builderType = createBuilder.getReturnType();
			Object builder = createBuilder.invoke(null);
			builder = builderType.getMethod(style == Style.AOSP ? "aosp" : "google").invoke(builder);
			builder = builderType.getMethod("maxLineLength", int.class).invoke(builder, maxLineLength);
			return (Style) builderType.getMethod("build").invoke(builder);
		} catch (NoSuchMethodException e) {
			throw new IllegalArgumentException(
					"maxLineLength requires google-java-format 1.37.0 or later (you are using " + version + ")", e);
		} catch (IllegalAccessException | InvocationTargetException e) {
			Throwable cause = e instanceof InvocationTargetException ? e.getCause() : e;
			throw new IllegalArgumentException("Failed to apply maxLineLength " + maxLineLength, cause);
		}
	}

	@Override
	@Nonnull
	public String apply(@Nonnull String input) throws Exception {
		String formatted = formatter.formatSource(input);
		String removedUnused = RemoveUnusedImports.removeUnusedImports(formatted);
		String sortedImports = ImportOrderer.reorderImports(removedUnused, reorderImports ? formatterStyle : Style.GOOGLE);
		return reflowLongStrings(sortedImports);
	}

	private String reflowLongStrings(String input) throws FormatterException {
		if (reflowStrings) {
			return StringWrapper.wrap(input, formatter);
		} else {
			return input;
		}
	}
}
